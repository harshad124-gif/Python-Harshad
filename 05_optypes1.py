#comparison or relational operators
a=50
b=20
print(a == b) #false, because a is not equal to b {ye operator check karta hai ki a aur b equal hai ya nahi}
print(a != b) #true, because a is not equal to b {ye operator check karta hai ki a aur b equal nahi hai ya nahi}
print(a > b) #true, because a is greater than b {ye operator check karta hai ki a b se bada hai ya nahi}
print(a < b) #false, because a is not less than b {ye operator check karta hai ki a b se chhota hai ya nahi}
print(a >= b) #true, because a is greater than or equal to b    {ye operator check karta hai ki a b se bada hai ya a b ke barabar hai ya nahi}
print(a <= b) #false, because a is not less than or equal to b {ye operator check karta hai ki a b se chhota hai ya a b ke barabar hai ya nahi}








