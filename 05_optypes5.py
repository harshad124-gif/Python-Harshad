#for or operator

val1=True
val2=False
print("or operator : ", val1 or val2)                    #true, because val1 is true {ye operator check karta hai ki dono val1 aur val2 me se koi bhi ek true hai ya nahi}

val1=False
val2=False
print("or operator : ", val1 or val2)                    #false, because both val1 and val2 are false {ye operator check karta hai ki dono val1 aur val2 me se koi bhi ek true hai ya nahi}