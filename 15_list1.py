#List in Python
marks =  [94, 85, 78, 92, 88]
print(marks)
print(len(marks))       # Prints the number of elements in the list


#How to access elements in a list
print(marks[0])         # Prints the first element
print(marks[1])         # Prints the second element
print(marks[2])         # Prints the third element
print(marks[3])         # Prints the fourth element
print(marks[4])         # Prints the fifth element

#Negative indexing
print(marks[-1])        # Prints the last element

